export function findMatchingChannel(query, videos = []) {
  if (!query || typeof query !== 'string') return null
  const q = query.trim().toLowerCase()
  if (!q) return null

  const clean = q.replace(/\b(channel|vlogs|vlog|videos|video|official|yt)\b/g, '').trim()

  // 1. Direct match in KNOWN_CHANNELS
  for (const channel of KNOWN_CHANNELS) {
    if (channel.name.toLowerCase() === q || channel.handle.toLowerCase() === q || channel.keywords.some((kw) => kw === q || kw === clean || q.includes(kw))) {
      return channel
    }
  }

  // 2. Match against CHANNEL_SECTIONS
  for (const section of CHANNEL_SECTIONS) {
    for (const [name, subs, imgNum] of section.channels) {
      const lowerName = name.toLowerCase()
      if (lowerName === q || lowerName === clean || q.includes(lowerName) || (clean.length > 2 && lowerName.includes(clean))) {
        return {
          id: name.toLowerCase().replace(/[^a-z0-9]/g, '-'),
          name,
          handle: `@${name.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
          subscribers: `${subs} subscribers`,
          avatar: `https://i.pravatar.cc/160?img=${imgNum}`,
          description: `Official channel of ${name}. Watch trending videos, playlists, and latest uploads.`,
          verified: true,
        }
      }
    }
  }

  // 3. Match against video channels in current search results
  if (videos && videos.length > 0) {
    // Count channel occurrences in results
    const channelCounts = {}
    const channelMap = {}
    for (const vid of videos) {
      const cName = vid.channel_name || vid.channelTitle || vid.channel
      if (!cName) continue
      channelCounts[cName] = (channelCounts[cName] || 0) + 1
      if (!channelMap[cName]) channelMap[cName] = vid
    }

    // Find if clean query matches any channel name in results
    for (const [cName, vid] of Object.entries(channelMap)) {
      const lowerC = cName.toLowerCase()
      if (lowerC === q || lowerC === clean || q.includes(lowerC) || (clean.length > 3 && lowerC.includes(clean))) {
        return {
          id: vid.channel_id || vid.channelId || cName.toLowerCase().replace(/[^a-z0-9]/g, '-'),
          name: cName,
          handle: vid.channel_handle || `@${cName.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
          subscribers: vid.subscribers ? `${vid.subscribers} subscribers` : '1.5M subscribers',
          avatar: vid.channel_avatar || `https://i.pravatar.cc/160?u=${encodeURIComponent(cName)}`,
          description: vid.description || `Welcome to ${cName}. Official channel featuring all latest videos and updates.`,
          verified: true,
        }
      }
    }

    // If the top 3 videos are predominantly from the same channel and query mentions channel
    if (q.includes('channel') || q.includes('vlog')) {
      const topChannel = videos[0]?.channel_name || videos[0]?.channelTitle
      if (topChannel) {
        const vid = videos[0]
        return {
          id: vid.channel_id || vid.channelId || topChannel.toLowerCase().replace(/[^a-z0-9]/g, '-'),
          name: topChannel,
          handle: vid.channel_handle || `@${topChannel.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
          subscribers: vid.subscribers ? `${vid.subscribers} subscribers` : '2.4M subscribers',
          avatar: vid.channel_avatar || `https://i.pravatar.cc/160?u=${encodeURIComponent(topChannel)}`,
          description: vid.description || `Welcome to ${topChannel}. Official channel featuring all latest videos and updates.`,
          verified: true,
        }
      }
    }
  }

  return null
}
